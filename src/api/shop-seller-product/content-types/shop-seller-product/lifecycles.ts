// ─────────────────────────────────────────────────────────────
// Lifecycle hooks ל-shop-seller-product.
//
// אין כאן התראה על הגשה: בחנות החירות מאשרים **חנות, לא מוצר**. ההתראה
// למנהלים על חנות חדשה שממתינה לאישור יושבת ב-lifecycle של shop-store,
// וגם האישור האוטומטי של כל מוצרי החנות ברגע שהיא מאושרת.
//
// מוצר שנוצר כאן הוא אחד משניים, ובשניהם אין למנהל מה לעשות:
//   • החנות מאושרת → המוצר כבר על המדף.
//   • החנות ממתינה → המוצר ממתין איתה, וההתראה על החנות כבר נשלחה.
// ─────────────────────────────────────────────────────────────

export default {
  async afterCreate(event: { result: { documentId: string; status?: string } }) {
    const s = event.result;
    strapi.log.info(
      `[shop-seller-product] מוצר ${s.documentId} נוצר בסטטוס ${s.status ?? '?'} — נגזר מהחנות, בלי אישור מוצר`
    );
  },
};
